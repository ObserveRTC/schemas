import {
	isArray,
	isEnum,
	isFieldRequired,
	isMap,
	isNullType,
	isRecord,
	isUnion,
	type AvroRecord,
	type AvroType,
} from '../../avro/schema.js';
import type { Logger } from '../../core/logger.js';

/**
 * How a field is represented in C++ regardless of its Avro type.
 *
 * - `json`: an opaque `nlohmann::json` (free-form objects: `attachments`, `payload`).
 * - `double`: a `double`; a whole value is written back as an integer, so a field whose wire
 *   type is `long` (`timestamp`) stays a valid long while keeping sub-millisecond precision.
 * - `string`: a `std::string`.
 *
 * Keyed like the TypeScript overrides: a bare field name, or `Record.field`, which wins.
 */
export type CppFieldKind = 'json' | 'double' | 'string';
export type CppFieldTypeOverrides = ReadonlyMap<string, CppFieldKind>;

export interface CppOptions {
	readonly schemaVersion: string;
	readonly emitDocs: boolean;
	/** `observertc` or `observertc::schemas`, nested namespaces allowed. */
	readonly namespace: string;
	readonly fieldTypeOverrides: CppFieldTypeOverrides;
	readonly enumSymbolOverrides: ReadonlyMap<string, (symbols: readonly string[]) => string[]>;
	/** Whether a module gets its own `SchemaVersion` constant (one module owns it). */
	readonly includeSchemaVersion: (schemaName: string) => boolean;
	/** File name of the shared JSON helpers header the modules include. */
	readonly supportHeader: string;
	readonly logger: Logger;
}

export interface CppModule {
	/** The header source, ready to be written to disk. */
	readonly code: string;
	/** Every struct the header declares, in declaration order. */
	readonly exports: string[];
}

/** A scalar C++ representation. */
type Scalar = 'int64_t' | 'double' | 'bool' | 'std::string';

/** The C++ shape of one field. */
type CppType =
	| { kind: 'scalar'; type: Scalar; wholeOrFraction: boolean }
	| { kind: 'json' }
	| { kind: 'record'; name: string }
	| { kind: 'vector'; item: CppType }
	| { kind: 'map'; value: CppType };

interface CppField {
	readonly name: string;
	/** The member name; differs from `name` only for a C++ keyword. */
	readonly member: string;
	readonly type: CppType;
	readonly optional: boolean;
	readonly doc?: string;
}

interface CppStruct {
	readonly name: string;
	doc?: string;
	readonly fields: CppField[];
}

const PRIMITIVE_CPP_TYPES: Readonly<Record<string, Scalar>> = {
	boolean: 'bool',
	string: 'std::string',
	int: 'int64_t',
	long: 'int64_t',
	float: 'double',
	double: 'double',
	// `bytes` is only ever used for base64/opaque payloads in these schemas.
	bytes: 'std::string',
};

const CPP_KEYWORDS = new Set([
	'alignas', 'alignof', 'and', 'asm', 'auto', 'bool', 'break', 'case', 'catch', 'char', 'class',
	'const', 'constexpr', 'continue', 'default', 'delete', 'do', 'double', 'else', 'enum', 'explicit',
	'export', 'extern', 'false', 'float', 'for', 'friend', 'goto', 'if', 'inline', 'int', 'long',
	'mutable', 'namespace', 'new', 'noexcept', 'not', 'nullptr', 'operator', 'or', 'private',
	'protected', 'public', 'register', 'return', 'short', 'signed', 'sizeof', 'static', 'struct',
	'switch', 'template', 'this', 'throw', 'true', 'try', 'typedef', 'typeid', 'typename', 'union',
	'unsigned', 'using', 'virtual', 'void', 'volatile', 'while', 'xor',
]);

/**
 * Render one Avro record as a self-contained, header-only C++ module: a struct per record it
 * reaches, each with `ToJson()` and a tolerant `FromJson()`, and (for the owning schema) the
 * `SchemaVersion` constant. The C++ counterpart of {@link generateTypeScriptModule}.
 */
export function generateCppModule(schema: AvroRecord, options: CppOptions): CppModule {
	const structs: CppStruct[] = [];
	const seen = new Set<string>();

	collectStruct(schema, options, structs, seen);

	const guard = `OBSERVERTC_SCHEMAS_${toMacroCase(schema.name)}_HPP`;
	const namespaces = options.namespace.split('::');
	const lines: string[] = [];

	lines.push(
		'// GENERATED FILE - DO NOT EDIT.',
		`// Generated by observertc-schemas from schema version ${options.schemaVersion}.`,
		'',
		`#ifndef ${guard}`,
		`#define ${guard}`,
		'',
		`#include "${options.supportHeader}"`,
		'',
		'#include <nlohmann/json.hpp>',
		'',
		'#include <cstdint>',
		'#include <map>',
		'#include <optional>',
		'#include <string>',
		'#include <vector>',
		'',
		...namespaces.map((name) => `namespace ${name} {`),
		'',
	);

	if (options.includeSchemaVersion(schema.name)) {
		lines.push(`constexpr const char* SchemaVersion = "${options.schemaVersion}";`, '');
	}

	// Collected outermost-first while walking; declared innermost-first so a struct is complete
	// before the struct that holds it by value.
	const ordered = [...structs].reverse();

	for (const struct of ordered) {
		lines.push(...renderDeclaration(struct, options));
	}
	for (const struct of ordered) {
		lines.push(...renderDefinitions(struct));
	}

	lines.push(...[...namespaces].reverse().map((name) => `} // namespace ${name}`), '', `#endif // ${guard}`, '');

	return { code: lines.join('\n'), exports: ordered.map((struct) => struct.name) };
}

/**
 * The JSON helpers every generated header includes: tolerant readers (a number may arrive as a
 * string, as older libwebrtc builds serialise 64-bit members) and the whole-or-fraction writer.
 */
export function generateCppSupportHeader(options: Pick<CppOptions, 'namespace' | 'schemaVersion'>): string {
	const namespaces = options.namespace.split('::');

	return [
		'// GENERATED FILE - DO NOT EDIT.',
		`// Generated by observertc-schemas from schema version ${options.schemaVersion}.`,
		'',
		'#ifndef OBSERVERTC_SCHEMAS_JSON_SUPPORT_HPP',
		'#define OBSERVERTC_SCHEMAS_JSON_SUPPORT_HPP',
		'',
		'#include <nlohmann/json.hpp>',
		'',
		'#include <cmath>',
		'#include <cstdint>',
		'#include <map>',
		'#include <optional>',
		'#include <string>',
		'#include <vector>',
		'',
		...namespaces.map((name) => `namespace ${name} {`),
		'namespace detail {',
		'',
		'/** A JSON value as T, or nullopt when it is absent or of another type. */',
		'template<typename T>',
		'std::optional<T> As(const nlohmann::json& value);',
		'',
		'template<>',
		'inline std::optional<double> As<double>(const nlohmann::json& value)',
		'{',
		'\tif (value.is_number())',
		'\t{',
		'\t\tconst auto number = value.get<double>();',
		'',
		'\t\treturn std::isfinite(number) ? std::optional<double>(number) : std::nullopt;',
		'\t}',
		'\tif (value.is_string())',
		'\t{',
		'\t\ttry',
		'\t\t{',
		'\t\t\tsize_t position{ 0 };',
		'\t\t\tconst auto& text  = value.get_ref<const std::string&>();',
		'\t\t\tconst auto number = std::stod(text, &position);',
		'',
		'\t\t\tif (position == text.size() && std::isfinite(number))',
		'\t\t\t{',
		'\t\t\t\treturn number;',
		'\t\t\t}',
		'\t\t}',
		'\t\tcatch (...)',
		'\t\t{',
		'\t\t}',
		'\t}',
		'',
		'\treturn std::nullopt;',
		'}',
		'',
		'template<>',
		'inline std::optional<int64_t> As<int64_t>(const nlohmann::json& value)',
		'{',
		'\tif (value.is_number_integer() || value.is_number_unsigned())',
		'\t{',
		'\t\treturn value.get<int64_t>();',
		'\t}',
		'',
		'\tconst auto number = As<double>(value);',
		'',
		'\treturn number ? std::optional<int64_t>(static_cast<int64_t>(*number)) : std::nullopt;',
		'}',
		'',
		'template<>',
		'inline std::optional<bool> As<bool>(const nlohmann::json& value)',
		'{',
		'\treturn value.is_boolean() ? std::optional<bool>(value.get<bool>()) : std::nullopt;',
		'}',
		'',
		'template<>',
		'inline std::optional<std::string> As<std::string>(const nlohmann::json& value)',
		'{',
		'\treturn value.is_string() ? std::optional<std::string>(value.get<std::string>()) : std::nullopt;',
		'}',
		'',
		'/** The member `key` of `object` as T, or nullopt. */',
		'template<typename T>',
		'std::optional<T> Read(const nlohmann::json& object, const char* key)',
		'{',
		'\tconst auto it = object.find(key);',
		'',
		'\treturn it == object.end() ? std::nullopt : As<T>(*it);',
		'}',
		'',
		'/** An array member, keeping the items that read as T. */',
		'template<typename T>',
		'std::optional<std::vector<T>> ReadVector(const nlohmann::json& object, const char* key)',
		'{',
		'\tconst auto it = object.find(key);',
		'',
		'\tif (it == object.end() || !it->is_array())',
		'\t{',
		'\t\treturn std::nullopt;',
		'\t}',
		'',
		'\tstd::vector<T> result;',
		'',
		'\tfor (const auto& item : *it)',
		'\t{',
		'\t\tif (auto value = As<T>(item))',
		'\t\t{',
		'\t\t\tresult.push_back(std::move(*value));',
		'\t\t}',
		'\t}',
		'',
		'\treturn result;',
		'}',
		'',
		'/** A map member, keeping the entries that read as T. */',
		'template<typename T>',
		'std::optional<std::map<std::string, T>> ReadMap(const nlohmann::json& object, const char* key)',
		'{',
		'\tconst auto it = object.find(key);',
		'',
		'\tif (it == object.end() || !it->is_object())',
		'\t{',
		'\t\treturn std::nullopt;',
		'\t}',
		'',
		'\tstd::map<std::string, T> result;',
		'',
		'\tfor (const auto& [name, item] : it->items())',
		'\t{',
		'\t\tif (auto value = As<T>(item))',
		'\t\t{',
		'\t\t\tresult.emplace(name, std::move(*value));',
		'\t\t}',
		'\t}',
		'',
		'\treturn result;',
		'}',
		'',
		'/** A whole number as an integer, anything else as a double. */',
		'inline nlohmann::json WholeOrFraction(double value)',
		'{',
		'\tif (std::isfinite(value) && std::floor(value) == value && std::abs(value) < 9007199254740992.0)',
		'\t{',
		'\t\treturn static_cast<int64_t>(value);',
		'\t}',
		'',
		'\treturn value;',
		'}',
		'',
		'} // namespace detail',
		...[...namespaces].reverse().map((name) => `} // namespace ${name}`),
		'',
		'#endif // OBSERVERTC_SCHEMAS_JSON_SUPPORT_HPP',
		'',
	].join('\n');
}

function collectStruct(record: AvroRecord, options: CppOptions, structs: CppStruct[], seen: Set<string>): CppStruct {
	const struct: CppStruct = {
		name: record.name,
		doc: options.emitDocs ? record.doc : undefined,
		fields: [],
	};

	seen.add(record.name);
	structs.push(struct);

	for (const field of record.fields) {
		const fieldDoc = options.emitDocs ? field.doc : undefined;
		const override = options.fieldTypeOverrides.get(`${record.name}.${field.name}`)
			?? options.fieldTypeOverrides.get(field.name);
		const branches = (isUnion(field.type) ? field.type : [field.type]).filter((branch) => !isNullType(branch));
		const nullable = isUnion(field.type) && branches.length !== field.type.length;

		let type: CppType;
		let doc = fieldDoc;

		if (override !== undefined) {
			type = overrideType(override, branches);
		} else if (branches.length !== 1) {
			options.logger.warn(`${record.name}.${field.name}: a union of ${branches.length} types is carried as JSON`);
			type = { kind: 'json' };
		} else {
			const mapped = mapType(branches[0]!, options, structs, seen, fieldDoc, `${record.name}.${field.name}`);

			type = mapped.type;
			if (mapped.enumSymbols) {
				doc = [fieldDoc, `One of: ${mapped.enumSymbols.join(', ')}.`].filter(Boolean).join(' ');
			}
		}

		struct.fields.push({
			name: field.name,
			member: CPP_KEYWORDS.has(field.name) ? `${field.name}_` : field.name,
			type,
			// JSON carries its own absence (null), so it is never wrapped.
			optional: type.kind !== 'json' && (nullable || !isFieldRequired(field)),
			doc: options.emitDocs ? doc : undefined,
		});
	}

	return struct;
}

function overrideType(kind: CppFieldKind, branches: AvroType[]): CppType {
	switch (kind) {
		case 'json':
			return { kind: 'json' };
		case 'string':
			return { kind: 'scalar', type: 'std::string', wholeOrFraction: false };
		case 'double': {
			// Written back as an integer when whole, if the wire type is integral.
			const integral = branches.some((branch) => branch === 'long' || branch === 'int');

			return { kind: 'scalar', type: 'double', wholeOrFraction: integral };
		}
	}
}

interface MappedType {
	type: CppType;
	enumSymbols?: string[];
}

function mapType(
	type: AvroType,
	options: CppOptions,
	structs: CppStruct[],
	seen: Set<string>,
	fieldDoc: string | undefined,
	where: string,
): MappedType {
	if (isUnion(type)) {
		const branches = type.filter((branch) => !isNullType(branch));

		if (branches.length === 1) return mapType(branches[0]!, options, structs, seen, fieldDoc, where);

		options.logger.warn(`${where}: a nested union of ${branches.length} types is carried as JSON`);
		return { type: { kind: 'json' } };
	}

	if (isArray(type)) {
		const item = mapType(type.items, options, structs, seen, fieldDoc, where);

		if (item.type.kind === 'vector' || item.type.kind === 'map') {
			options.logger.warn(`${where}: nested containers are carried as JSON`);
			return { type: { kind: 'json' } };
		}

		return { type: { kind: 'vector', item: item.type }, enumSymbols: item.enumSymbols };
	}

	if (isMap(type)) {
		const value = mapType(type.values, options, structs, seen, fieldDoc, where);

		if (value.type.kind !== 'scalar') {
			// A map of records (`AnyValue`) or of containers describes free-form JSON.
			return { type: { kind: 'json' } };
		}

		return { type: { kind: 'map', value: value.type } };
	}

	if (isEnum(type)) {
		const rewrite = options.enumSymbolOverrides.get(type.name);

		return {
			type: { kind: 'scalar', type: 'std::string', wholeOrFraction: false },
			enumSymbols: rewrite ? rewrite(type.symbols) : [...type.symbols],
		};
	}

	if (isRecord(type)) {
		if (!seen.has(type.name)) {
			const struct = collectStruct(type, options, structs, seen);

			if (!struct.doc && options.emitDocs) struct.doc = fieldDoc;
		}

		return { type: { kind: 'record', name: type.name } };
	}

	if (typeof type === 'string') {
		const primitive = PRIMITIVE_CPP_TYPES[type];

		if (primitive) return { type: { kind: 'scalar', type: primitive, wholeOrFraction: false } };

		// A reference to a named type declared earlier in the schema.
		if (seen.has(type)) return { type: { kind: 'record', name: type } };

		options.logger.warn(`${where}: no C++ mapping for Avro type "${type}", carried as JSON`);
		return { type: { kind: 'json' } };
	}

	options.logger.warn(`${where}: unsupported Avro type ${JSON.stringify(type)}, carried as JSON`);
	return { type: { kind: 'json' } };
}

function cppTypeName(type: CppType): string {
	switch (type.kind) {
		case 'scalar':
			return type.type;
		case 'json':
			return 'nlohmann::json';
		case 'record':
			return type.name;
		case 'vector':
			return `std::vector<${cppTypeName(type.item)}>`;
		case 'map':
			return `std::map<std::string, ${cppTypeName(type.value)}>`;
	}
}

function memberDeclaration(field: CppField): string {
	const typeName = cppTypeName(field.type);

	if (field.optional) return `std::optional<${typeName}> ${field.member};`;
	if (field.type.kind === 'scalar') {
		const initial = { int64_t: '0', double: '0.0', bool: 'false', 'std::string': '' }[field.type.type];

		return initial ? `${typeName} ${field.member}{ ${initial} };` : `${typeName} ${field.member};`;
	}

	return `${typeName} ${field.member};`;
}

function renderDeclaration(struct: CppStruct, options: CppOptions): string[] {
	const lines: string[] = [];

	if (struct.doc) lines.push('/**', ` * ${struct.doc}`, ' */');
	lines.push(`struct ${struct.name}`, '{');

	for (const field of struct.fields) {
		if (field.doc && options.emitDocs) lines.push('\t/**', `\t * ${field.doc}`, '\t */');
		lines.push(`\t${memberDeclaration(field)}`);
		if (field.doc && options.emitDocs) lines.push('');
	}

	if (struct.fields.length > 0 && !(struct.fields.at(-1)?.doc && options.emitDocs)) lines.push('');
	lines.push(
		'\t/** This record as JSON; absent optional fields are left out. */',
		'\tnlohmann::json ToJson() const;',
		'',
		'\t/** Reads a record from JSON. A missing or mistyped field reads as absent. */',
		`\tstatic ${struct.name} FromJson(const nlohmann::json& json);`,
		'};',
		'',
	);

	return lines;
}

/** Statements writing `expression` (of `type`) into `target`. */
function toJsonValue(type: CppType, expression: string): string {
	switch (type.kind) {
		case 'scalar':
			return type.wholeOrFraction ? `detail::WholeOrFraction(${expression})` : expression;
		case 'json':
			return expression;
		case 'record':
			return `${expression}.ToJson()`;
		case 'map':
			return expression;
		case 'vector':
			if (type.item.kind === 'record' || (type.item.kind === 'scalar' && type.item.wholeOrFraction)) {
				return `[&]() { auto items = nlohmann::json::array(); for (const auto& item : ${expression}) items.push_back(${toJsonValue(type.item, 'item')}); return items; }()`;
			}
			return expression;
	}
}

function renderToJson(field: CppField): string[] {
	const key = JSON.stringify(field.name);

	if (field.type.kind === 'json') {
		return [`\tif (!${field.member}.is_null())`, '\t{', `\t\tjson[${key}] = ${field.member};`, '\t}'];
	}
	if (field.optional) {
		return [
			`\tif (${field.member}.has_value())`,
			'\t{',
			`\t\tjson[${key}] = ${toJsonValue(field.type, `(*${field.member})`)};`,
			'\t}',
		];
	}

	return [`\tjson[${key}] = ${toJsonValue(field.type, field.member)};`];
}

/** Statements reading `field` from `json` into `result`. */
function renderFromJson(field: CppField): string[] {
	const key = JSON.stringify(field.name);
	const target = `result.${field.member}`;
	const type = field.type;

	if (type.kind === 'json') {
		return [
			`\tif (auto it = json.find(${key}); it != json.end() && !it->is_null())`,
			'\t{',
			`\t\t${target} = *it;`,
			'\t}',
		];
	}

	let reader: string;

	switch (type.kind) {
		case 'scalar':
			reader = `detail::Read<${type.type}>(json, ${key})`;
			break;
		case 'map':
			reader = `detail::ReadMap<${cppTypeName(type.value)}>(json, ${key})`;
			break;
		case 'record':
			return [
				`\tif (auto it = json.find(${key}); it != json.end() && it->is_object())`,
				'\t{',
				`\t\t${target} = ${type.name}::FromJson(*it);`,
				'\t}',
			];
		case 'vector':
			if (type.item.kind === 'record') {
				return [
					`\tif (auto it = json.find(${key}); it != json.end() && it->is_array())`,
					'\t{',
					`\t\tstd::vector<${type.item.name}> items;`,
					'',
					'\t\tfor (const auto& item : *it)',
					'\t\t{',
					`\t\t\titems.push_back(${type.item.name}::FromJson(item));`,
					'\t\t}',
					'',
					`\t\t${target} = std::move(items);`,
					'\t}',
				];
			}
			if (type.item.kind !== 'scalar') {
				// Unreachable: mapType carries nested containers as JSON.
				return [];
			}
			reader = `detail::ReadVector<${type.item.type}>(json, ${key})`;
			break;
	}

	if (field.optional) return [`\t${target} = ${reader};`];

	return [`\tif (auto value = ${reader})`, '\t{', `\t\t${target} = std::move(*value);`, '\t}'];
}

function renderDefinitions(struct: CppStruct): string[] {
	const lines: string[] = [];

	lines.push(`inline nlohmann::json ${struct.name}::ToJson() const`, '{', '\tauto json = nlohmann::json::object();', '');
	for (const field of struct.fields) lines.push(...renderToJson(field));
	lines.push('', '\treturn json;', '}', '');

	lines.push(`inline ${struct.name} ${struct.name}::FromJson(const nlohmann::json& json)`, '{', `\t${struct.name} result;`, '');
	lines.push('\tif (!json.is_object())', '\t{', '\t\treturn result;', '\t}', '');
	for (const field of struct.fields) lines.push(...renderFromJson(field));
	lines.push('', '\treturn result;', '}', '');

	return lines;
}

function toMacroCase(name: string): string {
	return name.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toUpperCase();
}
